"""Generate reproducible, synthetic browser-weapon oracles from the Python engine.

Run with the project's Python environment. No player records are read.
The default ten-pool distribution is a fixed deterministic DP table; keeping it
as an asset avoids repeating a two-dimensional convolution on every device.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import random
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "tools/gacha_rating_app"), str(ROOT / "tools/weapon_score_v2")]
from potential_profile_score import parse_profile, reference_profile_moments
from ten_pool_reference import _reference_cached
from weapon_scoring import score_weapon_record


def generate_reference():
    data = {}
    for name, ref in zip(("six_star", "signature"), _reference_cached(10)):
        data[name] = {
            "rows": [[ratio.numerator, ratio.denominator, float(p)]
                     for ratio, p in zip(ref.fractions, ref.pmf)],
            "expected_rate": ref.expected_rate,
            "expected_draws": ref.expected_draws,
            "expected_count": ref.expected_count,
        }
    source_hashes = {name: hashlib.sha256((ROOT / "tools/weapon_score_v2" / name).read_bytes()).hexdigest()
                     for name in ("scorer.py", "ten_pool_reference.py")}
    header = ("// Generated by browser/tests/weapon-oracle.py --reference.\n"
              "// Exact float64 DP, ten completed first-signature pools; no simulation or tail pruning.\n"
              "// Source SHA256: " + json.dumps(source_hashes, separators=(",", ":")) + "\n")
    target = ROOT / "browser/core/weapon-reference-data.js"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(header + "export const WEAPON_REFERENCE_DATA = "
                      + json.dumps(data, separators=(",", ":"), allow_nan=False) + ";\n", encoding="utf-8")
    print(f"Reference: {target.stat().st_size} bytes; {sum(len(v['rows']) for v in data.values())} ratios")


def generate_cases():
    # All values are deliberately synthetic and reproducible.
    records = [
        {"N": 1000, "K6": 55, "KU": 15},
        {"N": 1, "K6": 1, "KU": 1, "allowIndividualDraws": True},
        {"N": 30000, "K6": 0, "KU": 0},
        {"N": 30000, "K6": 30000, "KU": 30000},
        {"N": 1000, "K6": 55, "KU": 15, "profile": "12 5 1"},
        {"N": 1200, "K6": 65, "KU": 15, "profile": "12 6 1"},
        {"N": 2000, "K6": 100, "KU": 40, "profile": "11 5*7"},
        {"N": 2000, "K6": 100, "KU": 40, "profile": "11 7*5"},
        {"N": 340, "K6": 14, "KU": 5, "profile": "1 6"},
        {"N": 101, "K6": 4, "KU": 2, "profile": "2", "allowIndividualDraws": True},
        {"N": 500, "K6": 21, "KU": 8, "lossDraws": 80,
         "potentialConfig": {"totalTypes": 2, "counts": [0, 0, 0, 0, 1], "overflowCopies": 2}},
        {"N": 1200, "K6": 61, "KU": 15, "lossDraws": 117,
         "potentialConfig": {"totalTypes": 3, "counts": [1, 0, 0, 0, 2], "overflowCopies": 5, "overflowByType": [1, 4]}},
        {"N": 100, "K6": 0, "KU": 0, "lossDraws": 100},
        {"N": 100, "K6": 4, "KU": 2, "lossDraws": -1},
        {"N": 100, "K6": 4, "KU": 2, "lossDraws": 99},
        {"N": 100, "K6": 4, "KU": 2, "lossDraws": True},
    ]
    rng = random.Random(20261110)
    for _ in range(80):
        n = rng.randint(1, 3000) * 10
        k = rng.randint(0, min(n, round(n * .15)))
        u = rng.randint(0, k)
        records.append({"N": n, "K6": k, "KU": u, "lossDraws": rng.randint(0, n - u)})
    for _ in range(70):
        types = rng.randint(1, 20)
        potentials = [rng.randint(0, 12) for _ in range(types)]
        copies = sum(p + 1 for p in potentials)
        gifts = rng.randint(0, min(copies - types, 20))
        u = copies - gifts
        n = max(rng.randint(1, 1500) * 10, 180 + 160 * (gifts - 1) if gifts else 10, u * 10)
        k = rng.randint(u, min(n, u + 60))
        records.append({"N": n, "K6": k, "KU": u, "profile": " ".join(map(str, [types, *potentials])),
                        "lossDraws": rng.randint(0, n - u)})
    records += [
        {}, {"N": True, "K6": 0, "KU": 0}, {"N": 0, "K6": 0, "KU": 0},
        {"N": 30010, "K6": 0, "KU": 0}, {"N": 10, "K6": 11, "KU": 0},
        {"N": 101, "K6": 4, "KU": 2}, {"N": 100, "K6": 4, "KU": 2, "profile": []},
        {"N": 100, "K6": 4, "KU": 2, "profile": "1"},
        {"N": 100, "K6": 4, "KU": 2, "profile": "3"},
        {"N": 100, "K6": 4, "KU": 2, "profile": "1 5"},
        {"N": 30000, "K6": 200, "KU": 200, "profile": "1 199"},
        {"N": 30000, "K6": 40, "KU": 30, "profile": "31"},
    ]
    for config in ({}, {"totalTypes": True}, {"totalTypes": 0},
                   {"totalTypes": 2, "counts": [0, 0, 0, 0, 3]},
                   {"totalTypes": 2, "counts": [0, 0, 0, 0, 0], "overflowCopies": 1},
                   {"totalTypes": 2, "counts": [0, 0, 0, 0, 2], "overflowCopies": 1},
                   {"totalTypes": 2, "counts": [0, 0, 0, 0, 2], "overflowCopies": 1, "overflowByType": [1, 1]}):
        records.append({"N": 1000, "K6": 50, "KU": 10, "potentialConfig": config})
    cases = []
    for record in records:
        try:
            cases.append({"input": record, "expected": score_weapon_record(record)})
        except (ValueError, ArithmeticError) as exc:
            cases.append({"input": record, "error": str(exc)})
    profiles = ["0", "1", "3", "1 1", "1 5", "12 5 1", "11 5*7", "11 7*5", "1 10", "1 30"]
    cases_file = ROOT / "browser/tests/weapon-oracle.json"
    cases_file.write_text(json.dumps({
        "records": cases,
        "profiles": [{"input": p, "parsed": parse_profile(p), "moments": reference_profile_moments(p)} for p in profiles],
        "erfc": [[n / 80, math.erfc(n / 80)] for n in range(-1000, 2001)],
    }, ensure_ascii=False, allow_nan=False, separators=(",", ":")), encoding="utf-8")
    print(f"Oracle: {len(cases)} records, {len(profiles)} profiles; {cases_file.stat().st_size} bytes")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--reference", action="store_true")
    args = parser.parse_args()
    if args.reference:
        generate_reference()
    generate_cases()
